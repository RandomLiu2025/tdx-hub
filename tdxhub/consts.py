def _merge_hosts(*groups):
    """Merge host groups in priority order, deduplicating by IP and port."""

    merged = []
    seen = set()
    for group in groups:
        for host in group:
            endpoint = (host[1], int(host[2]))
            if endpoint in seen:
                continue
            seen.add(endpoint)
            merged.append(host)
    return merged


